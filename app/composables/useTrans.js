export function useTrans() {
  const { locale } = useLocale()

  function $t(key) {
    return messages[locale.value]?.[key] ?? messages['en']?.[key] ?? key
  }

  function tBy(obj) {
    return obj[locale.value] ?? obj['en'] ?? Object.values(obj)[0] ?? ''
  }

  return { $t, tBy, locale }
}
